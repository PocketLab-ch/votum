/**
 * Regelwerk, Fassung 2026-09-27.
 *
 * **Daten, kein Code** (AD-4). Diese Fassung belegt, was bisher unbelegt
 * dastand, und vervollständigt eine Karte, der eine von drei Bedingungen
 * fehlte. **Am Erfordernis ändert sich an keiner Stelle etwas.**
 *
 * Der Anlass ist der Durchgang durch die 24 offenen Rechtsfragen vom
 * 23.09.2026 (`2026-09-23-fragen-selbst-klaeren-bericht.md` im Verzeichnis
 * `.auftraege/` des Arbeitsverzeichnisses **über** diesem Repo, also nicht im
 * Quellarchiv) und
 * Die Produktentscheide dazu. Sechs Bundesgerichtsentscheide kamen an diesem Tag
 * neu in den Volltextbestand; drei davon tragen etwas, das hier schon stand,
 * aber schwächer oder gar nicht belegt war.
 *
 * ---
 *
 * **1. Der Ausweg bei der luxuriösen Massnahme hatte zwei von drei
 * Bedingungen.**
 *
 * `k-baulich-luxurioes-ausweg` bildet ZGB Art. 647e Abs. 2 ab und stand seit
 * der ersten Fassung im Baum. Die Begründung nannte «weder dauernd
 * beeinträchtigt noch belastet», die Hinweise die Kostenübernahme. **Rz. 135
 * ad Art. 712a nennt drei Bedingungen, und ausdrücklich kumulativ:**
 *
 * > «Mit einem qualifizierten Mehr nach Köpfen und nach Wertquoten können
 * > solche Massnahmen beschlossen werden, sofern **kumulativ**: allfällige
 * > Gegner der geplanten Massnahmen nicht in ihrem Nutzungs- und
 * > Gebrauchsrecht dauernd beeinträchtigt sind (Massstab: der
 * > Durchschnittsmensch; Zgraggen, Rz. 663); die übrigen Stockwerkeigentümer
 * > für bloss **vorübergehende Beeinträchtigung Ersatz leisten**; die übrigen
 * > Stockwerkeigentümer den Kostenanteil des oder der Gegner der geplanten
 * > Massnahmen übernehmen.»
 *
 * Die mittlere fehlte **auf der Ausweg-Karte**. Sie ist die einzige, die Geld
 * kostet, ohne dass jemand es merkt: Wer nur an den Kostenanteil denkt,
 * beschliesst den Ausweg, ohne den Ersatz zugesagt zu haben, und hat damit
 * eine der drei Bedingungen nicht erfüllt.
 *
 * **Die Reichweite dieser Lücke war in einem ersten Entwurf zu weit
 * beschrieben** («stand nirgends»). Der Code-Review hat nachgemessen: Der
 * Ersatz steht seit der Urfassung im Hilfetext der Frage `f1-4` und seit
 * 2026-08-15 am strengen Knoten. Er fehlte allein dort, wo nach der
 * Weichenstellung tatsächlich abgestimmt wird.
 *
 * **Dazu die Beweislast**, Rz. 135a ad Art. 712a: Wer behauptet, die
 * Voraussetzungen seien nicht erfüllt gewesen, hat das zu beweisen (Art. 8
 * ZGB; Kantonsgericht Graubünden ZK1 20 176 vom 14.12.2021, Erw. 5.3.2). Das
 * gehört auf die Karte, weil es die Richtung des Risikos umkehrt: Der Ausweg
 * ist nicht der wacklige Weg, für den ihn die bisherige Karte halten liess.
 *
 * **Die Fundstelle ist ein Kantonsgericht, nicht das Bundesgericht**, und der
 * Hinweis sagt das. Eine kantonale Erwägung als «das Gericht» auszugeben, ist
 * genau der Fehler, den die Fachprüfung an diesem Tag zweimal gefunden hat.
 *
 * ---
 *
 * **2. Der Trennungsvorschlag bekommt seinen Beleg — und seine Grenze.**
 *
 * `gemischteGeschaefte` empfiehlt seit der ersten Fassung, ein Vorhaben mit
 * mehreren Zwecken in zwei Traktanden zu trennen. Der Satz stand ohne
 * Fundstelle da. **Rz. 115a ad Art. 712a** trägt ihn:
 *
 * > «Bauprojekte können notwendige, nützliche und gleichzeitig auch luxuriöse
 * > bauliche Massnahmen enthalten. In einem solchen Fall ist **entweder** ein
 * > einstimmiger Beschluss für alle Massnahmen gemeinsam zu fassen **oder** es
 * > muss für jede Kategorie von Massnahmen eine separate Abstimmung
 * > durchgeführt werden […] mit dem jeweils entsprechenden
 * > Mehrheitserfordernis.»
 *
 * Und **BGer 5A_798/2010 E. 4.6.2** hält die Trennung für zumutbar, gegen den
 * Einwand, sie führe zur Lähmung: «Nel merito, la soluzione di sottoporre
 * all'assemblea ogni singolo intervento edilizio **non appare
 * irrealizzabile**.» Derselbe Absatz nennt Art. 647e Abs. 2 ausdrücklich als
 * den Weg, auf dem einem Eigentümer eine reine Verschönerung überhaupt
 * auferlegt werden kann — er trägt damit auch Punkt 1.
 *
 * **Die Grenze, und sie steht im Text der Karte nicht, weil sie nicht
 * hineinpasst, aber hier muss sie stehen:** Rz. 115a spricht von
 * **Bauprojekten** und von den drei baulichen Kategorien. Der Hinweis in
 * dieser Anwendung gilt für gemischte Geschäfte überhaupt. Für den baulichen
 * Fall ist er jetzt belegt, darüber hinaus bleibt er eine gut begründete
 * Empfehlung des Hauses. Deshalb nennt der Kartentext die Fundstelle **am
 * baulichen Beispiel** und nicht am allgemeinen Satz.
 *
 * Und ein Halbsatz aus E. 4.6.2, der in einen ersten Entwurf dieses Kopfs
 * nicht hineingehörte: «L'opinione dell'autorità cantonale poggia su
 * autorevole dottrina.» Das Bundesgericht **bestätigt** dort die Vorinstanz
 * und die Lehre, auf die sie sich stützt. Es stellt nicht selbst eine neue
 * Regel auf. Genau diese Verwechslung hat die Fachprüfung am 23.09.2026 in
 * der Empfehlung an zwei Stellen gefunden.
 *
 * ---
 *
 * **3. Ein publizierter Leitentscheid tritt neben einen schwachen Beleg.**
 *
 * Für den Stimmrechtsausschluss stützte sich das Haus bisher auf den
 * Beobachter-Ratgeber. Er ist keine Rechtsquelle, und die Fassung 2026-09-22
 * hat das für eine andere Karte schon festgehalten. **BGE 134 III 481** liegt
 * seit dem 23.09.2026 im Volltext vor und trägt zwei Sätze:
 *
 * **Der Ratgeber bleibt dabei in der Quellenliste stehen**, und ein erster
 * Entwurf dieses Kopfs behauptete, er werde «ersetzt». Er wird es nicht: Die
 * Liste wird nur ergänzt, und eine Fassung löscht keine Einträge früherer
 * Fassungen. Abgelöst ist er dort, wo er als **Beleg für eine Aussage**
 * stand, im Fragendokument. Wo er als Lektüre in der Liste steht, bleibt er.
 * Die Sätze:
 *
 *   - **E. 3.8:** Wer nach Art. 68 ZGB vom Stimmrecht ausgeschlossen ist, darf
 *     auch nicht **als Vertreter** eines anderen Stockwerkeigentümers stimmen
 *     (analog Art. 695 Abs. 1 OR, BGE 128 III 142 E. 3b).
 *   - **E. 3.9:** Die unter Verletzung von Art. 68 abgegebenen Stimmen sind
 *     «als ungültig zu betrachten und nicht zu zählen».
 *
 * Beides ist tragend: Die Beschlüsse Ziff. 3 und 4 wurden aufgehoben.
 *
 * **Was der Entscheid nicht sagt, und das gehört in dieselbe Zeile:** Ob ein
 * anwesender Ausgeschlossener im **Nenner** der Kopfmehrheit stehen bleibt.
 * E. 3.9 spricht über die abgegebenen Stimmen, nicht über die Bezugsgrösse,
 * und der Fall konnte die Frage nicht stellen: «Da diese beiden Personen
 * unbestrittenermassen die einzigen Teilnehmer der
 * Stockwerkeigentümerversammlung waren, ist der betreffende Beschluss nicht
 * zustande gekommen.» Es war niemand sonst im Saal. Die Frage bleibt offen und
 * bleibt auf der Liste an die Anwältin.
 *
 * Ein erster Entwurf dieser Fassung hat den Entscheid für die Bezugsgrösse in
 * Anspruch genommen. Die Sitzung website-aa hat widersprochen; die
 * Gegenmessung am Volltext gab ihr recht.
 *
 * ---
 *
 * **4. Die Revision steht in der Quellenliste, mit dem Vermerk, dass sie nicht
 * gilt.**
 *
 * Die Liste sagte bisher nur, die konsolidierte ZGB-Fassung enthalte die
 * laufende Revision nicht. Seit dem 23.09.2026 liegt der Entwurf im Repo
 * (BBl 2026 1517). Wer eine Karte prüft, soll die vier Stellen sehen, an denen
 * sich etwas ändern wird, **und den Satz, dass heute keine davon gilt**.
 *
 * Der Grund, warum das hier und nicht nur in einer Notiz steht: Eine
 * Fassungskennung bleibt für immer stehen (AD-4). Wer 2029 nachschlägt, warum
 * ein Beschluss von 2026 so gerechnet wurde, findet in der Quellenliste den
 * Stand des Rechts zu diesem Zeitpunkt — samt dem, was damals schon bekannt,
 * aber noch nicht in Kraft war.
 *
 * ---
 *
 * **Was diese Fassung ausdrücklich NICHT tut.**
 *
 * **Die zwei absoluten Schranken beim Rückkommen fehlen weiterhin.** Rz. 202a
 * ad Art. 712g: Verwaltungsbeschlüsse können jederzeit widerrufen oder
 * abgeändert werden, «soweit sie **keine Gestaltungswirkung** entfalten und
 * **nicht bereits realisiert** wurden». Die Anwendung kennt heute nur die
 * Schranke des erforderlichen Mehrs (`domain/rueckkommen.ts`) und zeigt für
 * jeden Fall eine erreichbare Zahl, auch dort, wo gar kein Mehr hilft.
 *
 * Das gehört hinein, aber **nicht als Daten**: Das Rückkommen hat keinen
 * Knoten im Baum, die Schranken wären eine Absage vor der Abstimmung, und das
 * ist Verhalten mit eigener Prüfung. Eigener Block, geführt in
 * `docs/befunde-rechtsfragen-2026-09-23.md`.
 *
 * **Und eine Fundstelle, die sich nicht nachprüfen liess.**
 * `domain/rueckkommen.ts` zitiert im Antragswortlaut wörtlich: ein früherer
 * Beschluss «bleibt nur soweit verbindlich, als er nicht durch einen späteren
 * Beschluss abgeändert wird» (5C.40/2005 E. 3). Der publizierte Auszug dieses
 * Entscheids (BGE 131 III 459) enthält **nur E. 5**; eine E. 3 steht dort
 * nicht, und die zitierten Wörter kommen im ganzen Text nicht vor. Auch
 * Wermelinger zitiert in Rz. 202a «Erw. 3» und meint damit das unpublizierte
 * Volltexturteil. **Das ist kein Beleg dafür, dass der Satz falsch ist** — es
 * ist ein Beleg dafür, dass wir ihn mit unserem Bestand nicht prüfen können.
 * Das Urteil 5C.40/2005 vom 16. Juni 2005 im Volltext zu beschaffen, ist ein
 * einzelner Abruf und steht auf der Quellenbedarfsliste.
 */
