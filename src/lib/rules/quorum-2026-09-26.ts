/**
 * Regelwerk, Fassung 2026-09-26.
 *
 * **Daten, kein Code** (AD-4). Diese Fassung berichtigt die Beispiele dreier
 * Karten: `k-grenzfall-nutzung` bekommt ein drittes und stellt die Reihenfolge
 * um, `k-zweckbestimmung` und `k-benutzungsweise` belegen denselben Entscheid
 * neu mit der Erwägung, die sein Ergebnis trägt. Alle drei Texte gehen über
 * den Abzug nach aussen. Die Weiche `f5-1` bleibt unangetastet, siehe unten.
 * Am Erfordernis ändert sich nichts.
 *
 * ---
 *
 * **Der Anlass, und diesmal richtig zugeschrieben.**
 *
 * Produktentscheid 23.09.2026: Die Karte soll ein Bild bekommen. Der Wunsch
 * stammt aus `docs/befunde-quorumkarten-2026-09-22.md`, wo er nach dem
 * Code-Review der Fassung 2026-09-24 als offene Textentscheidung vermerkt
 * wurde.
 *
 * **Er stammt nicht aus der Laienprüfung**, auch wenn ein erster Entwurf
 * dieses Kopfs das behauptete. Ihr Abschnitt zu dieser Karte hat genau einen
 * Befund, die Monatsfrist im Satz mit der höchsten Fachdichte, und schliesst
 * mit «Sonst ist die Karte gut». Eine Textentscheidung als Prüfbefund
 * auszugeben, verschiebt die Verantwortung dorthin, wo sie nicht liegt, und
 * wer später im Bericht nachschlägt, findet nichts.
 *
 * ---
 *
 * **Warum ein Beispiel und nicht ein Paar.**
 *
 * Ein erster Entwurf stellte zwei Beispiele gegenüber: Kinderbetreuung
 * zulassen als Zweckänderung, dieselbe Nutzung verbieten oder präzisieren als
 * keine. Der Code-Review hat das verworfen, und zu Recht: Die beiden Fälle
 * unterscheiden sich in **zwei** Dingen zugleich, in der Richtung (zulassen
 * gegen einschränken) und in der Breite der bisherigen Zweckbestimmung. Den
 * Ausgang trägt die Richtung, nicht die Breite: **Rz. 150d ad Art. 712a**
 * stellt für die nachträgliche Einschränkung eine eigene Regel auf, mit
 * eigenem Vorbehalt. Dass sie «unabhängig» von der Zweckbreite gälte, stand
 * in einem ersten Entwurf dieses Kopfs und steht nicht in der Quelle.
 *
 * Ein Paar, das zwei Dinge zugleich ändert, zeigt keine Grenze, sondern
 * erfindet eine. Der Leser hätte «zulassen ist streng, verbieten ist mild»
 * mitgenommen, und das sagt die Empfehlung derselben Karte gerade nicht.
 *
 * Dazu hätte die Gegenseite einen Vorbehalt gebraucht, den der Entwurf nicht
 * nannte: Wird eine Nutzungsmöglichkeit nachträglich eingeschränkt, ist zu
 * prüfen, ob die Einschränkung **erheblich** ist und damit doch Einstimmigkeit
 * verlangt (Rz. 150d, BGE 139 III 1 E. 4.4). Ohne ihn hätte das Beispiel dort
 * beruhigt, wo es warnen müsste.
 *
 * ---
 *
 * **Und der Wortlaut des Beispiels, am Entscheid aufgeschlagen statt aus dem
 * Vorschlag übernommen.**
 *
 * Der Vorschlag lautete «gewerbsmässige Kinderbetreuung in einer Wohnung,
 * obwohl der Eingriff klein wirkt». Beides trägt nicht. «Obwohl der Eingriff
 * klein wirkt» ist eine Deutung, die nirgends steht. Und ausschlaggebend war
 * nicht das Zulassen der Kinderbetreuung, sondern dass die Reglementsänderung
 * die Ruheauflage **strich**.
 *
 * BGer 5A_98/2017 E. 3.3 im Wortlaut: Das alte Reglement verlangte
 * ausdrücklich «tranquillité et absence de gêne liée aux bruits et
 * trépidations»; die Änderung beschränkte sich auf «bonne tenue» und schuf,
 * «vu la petite structure du bâtiment, trois étages, trois appartements», eine
 * Unvereinbarkeit mit der ursprünglichen Zweckbestimmung, «l'habitation dans
 * un environnement paisible».
 *
 * **Rz. 150d nennt dazu BGer 5A_127/2020 als endgültige Bestätigung.** Der
 * Entscheid liegt nicht im Repo, und die einzige Stelle, die ihn führt,
 * bezieht ihn auf die Unvereinbarkeit der Kinderbetreuung mit der Wohnnutzung,
 * also auf die Nutzungsfrage und nicht auf das Quorum. Er steht deshalb weder
 * im Kartentext noch hier als Beleg.
 *
 * Das ist das bessere Bild: Was wie eine kleine Änderung am Reglementstext
 * aussieht, kann die Zweckbestimmung kippen.
 *
 * ---
 *
 * **Was dieser Block ausdrücklich NICHT tut, und warum.**
 *
 * Die Fachprüfung hat beim Einbauen einen Bestandsbefund freigelegt: Die
 * Antwort «Der Zweck der Liegenschaft kippt, aus Wohnen wird Gewerbe» an der
 * Frage `f5-1` verengt die Zweckänderung auf einen Fall. Wer den Fall des
 * neuen Beispiels hat, verneint sie zu Recht und landet beim qualifizierten
 * Mehr, also beim Quorum, das das Bundesgericht aufgehoben hat.
 *
 * **Ein Entwurf hat die Antwortzeile geändert, und das war die falsche von
 * zwei Stellen.** Der Hilfetext eine Zeile darüber gibt für genau diesen Fall
 * Entwarnung: «Eine stille Praxis in einem Wohnhaus kippt den Charakter in
 * der Regel nicht.» Im Entscheid war die Praxis still, und entschieden wurde
 * er, weil die Reglementsänderung die Bedingung der Ruhe strich. Der
 * beruhigende Beispielsatz ist derselbe Sachverhalt, nur ohne das, was ihn
 * beruhigend macht.
 *
 * Die Laienprüfung hat dazu gemessen, dass die neue Antwortzeile für sie
 * **schlechter** beantwortbar war als die alte: Sie wiederholt die Frage als
 * Aussagesatz und nennt kein Merkmal, das sich nachschauen lässt. Die alte war
 * falsch, aber prüfbar. Ein Rechtsfehler gegen ein Verständlichkeitsproblem
 * getauscht ist kein guter Tausch.
 *
 * Die Zeile ist deshalb **unverändert**. Die Weiche ist ein eigener Block:
 * Sie entscheidet über das Quorum, sie braucht Hilfetext und Antworten
 * zusammen, und sie braucht einen Entwurf, den beide Zielgruppen anwenden
 * können. Geführt in `docs/befunde-quorumkarten-2026-09-22.md`.
 */
